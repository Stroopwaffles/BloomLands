/**
 * The game's music: one composed track per region, by day and by night. Each track is written out
 * like sheet music (a chord and a melody for every bar) and loops in an A–B form, so it plays the
 * same tune every time. All tunes are original to Bloom Lands.
 *
 * Notation:
 * - chords: one string per bar. "C" fills the bar; "Dm G" splits it evenly. "m" means minor.
 * - melody: one string per bar of "note:beats" tokens, e.g. "E5:1 G5:0.5 r:0.5". "r" is a rest.
 *   Note names use sharps (#) or flats (b), with the octave (C5 is the C above middle C).
 */

export type Accompaniment = 'arpeggio' | 'waltz' | 'bounce'

export interface TrackDef {
  id: string
  name: string
  bpm: number
  beatsPerBar: 3 | 4
  chords: string[]
  melody: string[]
  /** How the chords are played under the tune. */
  accompaniment: Accompaniment
  /** The tune's instrument. */
  lead: OscillatorType
  /** Brightness of the pad (lowpass cutoff, Hz). */
  padCutoff: number
}

